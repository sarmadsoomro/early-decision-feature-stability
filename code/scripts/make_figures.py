    tab_rfe(out, [(f"Day {d}, lag {lag}", f"oulad_day{d}_bootstrap_summary.json" if not lag else
                   os.path.join("lag14_boot", f"oulad_day{d}_tmalag14_bootstrap_summary.json"))
                  for d in [30, 60] for lag in [0, 14]], "tabS-lag-contrasts.tex")
    tab_cross(out)
    tab_cross(out, "_common", "tabS-cross-common.tex")
    tab_holdout_all(out)
    tabS_k_le_p3(out)
    tabS_cross_pairs(out)
    tabS_lag(out)
    tabS_cv_auc(out)
    tabS_bias(out)
    print("wrote", sorted(os.listdir(out)))
